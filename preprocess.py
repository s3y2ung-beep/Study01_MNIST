"""손글씨 그림을 MNIST 학습 데이터와 같은 모양(28x28)으로 바꾸는 전처리.

MNIST 원본은 숫자를 20x20 상자에 비율을 유지하며 줄여 넣은 뒤,
밝기의 무게중심이 28x28 칸의 한가운데에 오도록 옮긴 것이다.
그림판 그림도 같은 3단계를 거쳐야 모델이 잘 알아본다.
"""

import numpy as np
from PIL import Image

# MNIST 학습 데이터 전체의 밝기 평균과 표준편차 (정규화 상수)
정규화_평균 = 0.1307
정규화_표준편차 = 0.3081

# 숫자를 줄여 넣을 상자 크기와 최종 칸 크기
상자_크기 = 20
최종_크기 = 28


def 반올림(x):
    """0.5를 항상 위로 올리는 반올림 (자바스크립트 Math.round와 같은 규칙)."""
    return int(np.floor(x + 0.5))


def 전처리(그림: Image.Image):
    """흰 글씨/검은 바탕의 흑백 그림(모드 'L')을 받아 0~1 범위의 28x28 배열을 돌려준다.

    아무것도 그려지지 않았으면 None을 돌려준다.
    """
    배열 = np.asarray(그림.convert("L"), dtype=np.float32)

    # 1단계: 여백 자르기 (획이 있는 영역만 남김)
    행들 = np.where(배열.max(axis=1) > 0)[0]
    열들 = np.where(배열.max(axis=0) > 0)[0]
    if len(행들) == 0:
        return None
    위, 아래 = 행들[0], 행들[-1] + 1
    왼, 오른 = 열들[0], 열들[-1] + 1
    잘린 = 그림.convert("L").crop((왼, 위, 오른, 아래))

    # 2단계: 비율을 유지하며 긴 변이 20이 되도록 축소
    너비, 높이 = 잘린.size
    배율 = 상자_크기 / max(너비, 높이)
    새너비 = max(1, 반올림(너비 * 배율))
    새높이 = max(1, 반올림(높이 * 배율))
    작은 = np.asarray(잘린.resize((새너비, 새높이), Image.LANCZOS), dtype=np.float32) / 255.0

    # 3단계: 밝기 무게중심이 28x28의 중앙(14, 14)에 오도록 배치
    합 = 작은.sum()
    ys, xs = np.mgrid[0:새높이, 0:새너비]
    중심y = (ys * 작은).sum() / 합
    중심x = (xs * 작은).sum() / 합
    시작y = int(np.clip(반올림(최종_크기 / 2 - 중심y), 0, 최종_크기 - 새높이))
    시작x = int(np.clip(반올림(최종_크기 / 2 - 중심x), 0, 최종_크기 - 새너비))

    결과 = np.zeros((최종_크기, 최종_크기), dtype=np.float32)
    결과[시작y:시작y + 새높이, 시작x:시작x + 새너비] = 작은
    return 결과


def 정규화(배열28):
    """0~1 범위의 28x28 배열을 모델 입력용으로 정규화한다."""
    return (배열28 - 정규화_평균) / 정규화_표준편차
